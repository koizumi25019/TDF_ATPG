//=========================================================================
//  関数名 : make_test_set
//  機  能 : テスト集合に追加
//  戻り値 : なし
//  引  数 : ファイルポインタ
//=========================================================================
void make_test_set(FILE *fp_ts) {

	char str[50000];
	FILE*fp;

	if ((fp=fopen(tv_path, "r")) == NULL) {
		printf("【ERROR】:File open tv.txt(make_test_set.c)\n");
		exit(1);
	}

	while (fgets(str, 50000, fp) != NULL) {
		if ((strcmp(str, "\n")) != 0) {
			fprintf(fp_ts, "%s", str);
		}
	}

	fclose(fp);

}

//=========================================================================
//  関数名 : generate_test_vector
//  機  能 : clasp の結果からテストベクトルを生成する
//           generate_tv.exe は実行フォルダーに tv.txt を出力する(出力先は変えられない)ので、
//           その直後に中間生成フォルダー(tv_path)へ移し、実行フォルダーを汚さない・
//           古い tv.txt を取り違えないようにする
//  戻り値 : int 正常終了:SUCCESS , tv.txt が作られなかった:ERROR
//  引  数 : clasp の結果ファイル名
//=========================================================================
int generate_test_vector(const char* clasp_log) {
	char cmd[2048];
	FILE* fp;

	snprintf(cmd, sizeof(cmd), "generate_tv.exe %s %d", clasp_log, n_pi + n_dff);
	system(cmd);

	//generate_tv.exe の出力(実行フォルダーの tv.txt)を確認
	if ((fp = fopen("tv.txt", "r")) == NULL) {
		printf("【ERROR】:tv.txt was not generated by generate_tv.exe(make_test_set.c)\n");
		return ERROR;
	}
	fclose(fp);

	//中間生成フォルダーへ移動(Windowsでは移動先が既にあると rename が失敗するので先に消す)
	remove(tv_path);
	if (rename("tv.txt", tv_path) != 0) {
		printf("【ERROR】:Cannot move tv.txt to %s(make_test_set.c)\n", tv_path);
		return ERROR;
	}

	return SUCCESS;
}

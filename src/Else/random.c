//------------------------------------------------------------------------
//乱数(xorshift64*)
//標準の rand() は実装によって最大値が違う(MSVCは32767)ため、故障が3万個を超える回路で
//選び方が偏る。ここでは自前の乱数を使い、どの環境でも同じ種なら同じ並びになるようにする。
//------------------------------------------------------------------------
static unsigned long long rng_state = 88172645463325252ULL;

static unsigned long long rng_next(void) {
	unsigned long long x = rng_state;
	x ^= x >> 12;
	x ^= x << 25;
	x ^= x >> 27;
	rng_state = x;
	return x * 2685821657736338717ULL;
}

//===================================================
//関数名:rng_seed
//機能:乱数の種の設定
//戻り値：なし
//引数：種
//===================================================
void rng_seed(unsigned int seed) {
	int i;
	rng_state = ((unsigned long long)seed + 1ULL) * 0x9E3779B97F4A7C15ULL;
	if (rng_state == 0) rng_state = 88172645463325252ULL;
	for (i = 0; i < 8; i++) rng_next();	//種が近い値でも並びが似ないように数回進める
}

//===================================================
//関数名:rng_below
//機能:0以上 n 未満の乱数を返す
//戻り値：乱数
//引数：n (1以上)
//===================================================
unsigned int rng_below(unsigned int n) {
	return (unsigned int)((rng_next() >> 33) % n);	//上位31bitを使う
}

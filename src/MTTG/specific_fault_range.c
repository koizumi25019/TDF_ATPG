//===================================================
//関数名:specific_fault_range
//機能:故障範囲特定(故障信号線から到達可能な信号線を求め、故障回路用の添え字を割り当てる)
//戻り値：int 正常終了:SUCCESS(=0) , 異常終了:ERROR(=-1)
//引数：故障信号線
//===================================================
int specific_fault_range(NLIST* fault_net) {
	int i;
	NLIST* nlist;

	if (fault_net == NULL) return ERROR;

	fc_ppo = 0;//PPO数初期化

	//-----------------------------------------------
	//	故障回路の添え字とFAULT_PASSの初期化
	//-----------------------------------------------
	for (i = 0; i < n_net; i++) {
		nl[i].suf_fc = nl[i].suf_2t; //2時刻目の添え字で初期化
		nl[i].fault_pass = NO;
	}

	//-----------------------------------------------
	//故障信号線から到達可能な信号線の探索(幅優先)
	//-----------------------------------------------
	//到達可能：ある信号線がほかの信号線に影響を与える可能性があるかどうかを意味する
	//キューに入れる時点で fault_pass を YES にするので、同じ信号線は1度しかキューに入らない
	//(そのためキューの大きさは n_net+1 で足りる)
	fault_net->fault_pass = YES;
	enqueue(fault_net, 0);

	while (queue_emp() != 0) {
		nlist = dequeue();		//デキュー
		nlist->suf_fc = suffix;	//故障回路の添え字設定
		suffix++;				//添え字インクリメント
		if (nlist->ppo_flag != 1) {//PPO(疑似外部出力)より先へは影響を伝えない
			for (i = 0; i < nlist->n_out; i++) {//複数の出力なら、それぞれエンキュー
				if (nlist->out[i]->fault_pass == NO) {
					nlist->out[i]->fault_pass = YES;
					enqueue(nlist->out[i], 0);
				}
			}
		}
	}

	//故障回路に含まれるPPO数算出
	for (i = 0; i < n_net; i++) {
		if (nl[i].fault_pass == YES && nl[i].ppo_flag == 1) fc_ppo++;
	}

	return SUCCESS;
}

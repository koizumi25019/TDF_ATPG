//===================================================
//関数名:untest_check_wsa
//機能:WSA計算(高消費電力故障か否か)
//     →高消費故障の場合、テスト不能故障とみなす
//戻り値：int 低消費電力:SAT , 高消費電力:UNSAT , 判定できない:ERROR
//引数：対象故障,対象故障の前にある故障
//===================================================
int untest_check_wsa(UNDET_FAULT_LIST* node, UNDET_FAULT_LIST* pre_node) {
	int flag = check_wsa("high_tp.txt", "low_tp.txt");

	//高消費電力故障の場合→未検出故障リストから削除(高消費電力故障リストへ)
	if (flag == UNSAT) {
		ufl_free(node, pre_node, 1);
	}

	return flag;
}
